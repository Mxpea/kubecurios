const $SmokeDataComponents = Java.loadClass('net.minecraft.core.component.DataComponents')
const $SmokeItemLore = Java.loadClass('net.minecraft.world.item.component.ItemLore')
const $SmokeLoreList = Java.loadClass('java.util.ArrayList')
const $SmokeComponent = Java.loadClass('net.minecraft.network.chat.Component')

StartupEvents.registry('item', event => {
  event.create('kubecurios_smoke:combat_ring', 'kubecurios:curio')
    .slot('kubecurios_smoke_ring')
    .onHurtCommand('execute if entity @s[distance=..0.01] run effect give @s minecraft:resistance 1 0 true', 40)
    .outgoingDamagePercent(15)
    .incomingDamagePercent(-10)
    .incomingDamageTypePercent('#minecraft:is_fire', -25)
    .incomingDamageTypePercent('minecraft:fall', 10)
    .armor(2)
    .armorToughness(1.5)

  event.create('kubecurios_smoke:vulnerability_ring', 'kubecurios:curio')
    .slot('kubecurios_smoke_ring')
    .incomingDamagePercent(10)

  event.create('kubecurios_smoke:zero_chance_ring', 'kubecurios:curio')
    .slot('kubecurios_smoke_ring')
    .onHurtCommand('tag @s add kubecurios_zero_chance', 40, 0)

  var lore = new $SmokeLoreList()
  lore.add($SmokeComponent.literal('Manually added tooltip'))
  event.create('kubecurios_smoke:hidden_ring', 'kubecurios:curio')
    .slot('kubecurios_smoke_ring')
    .onHurtCommand('execute if entity @s[distance=..0.01] run tag @s add kubecurios_attacker', 40, 'attacker', 100)
    .outgoingDamagePercent(-20)
    .incomingDamagePercent(10)
    .armor(-1)
    .armorToughness(-0.5)
    .hideAttribute()
    .component($SmokeDataComponents.LORE, new $SmokeItemLore(lore))
})
